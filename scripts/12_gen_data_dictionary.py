def describe(path: Path, title: str, note: str = ""):
    df = pd.read_parquet(path)
    w(f"### `{title}` — {len(df):,} rows\n")
    if note:
        w(note + "\n")
    w("| Column | Type | Non-null | Distinct | Example / range |")
    w("|---|---|---|---|---|")
    for c in df.columns:
        s = df[c]
        nn = f"{100*s.notna().mean():.1f}%"
        nd = s.nunique(dropna=True)
        if pd.api.types.is_bool_dtype(s):
            ex = f"{s.mean():.1%} true"
        elif pd.api.types.is_numeric_dtype(s):
            v = s.dropna()
            ex = f"{v.min():.2f} … {v.max():.2f}" if len(v) else "—"
        else:
            vals = s.dropna().astype(str)
            ex = (", ".join(f"`{x}`" for x in vals.value_counts().head(3).index)
                  if nd <= 25 else (f"`{vals.iloc[0][:28]}`" if len(vals) else "—"))
        w(f"| `{c}` | {s.dtype} | {nn} | {nd:,} | {ex} |")
    w("")

